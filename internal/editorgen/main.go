// Command editorgen generates the typed editor interfaces and their private
// implementations. Run it from the module root with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"

	"mvdan.cc/gofumpt/format"
)

type (
	feature   struct{ fields, methods string }
	statement struct{ kind, features string }
	method    struct{ Signature, Body string }
)

type editor struct {
	Kind, Editor, Private, State string
	Methods                      []method
	Fields, Flags                []string
	Callbacks                    bool
	TableRefs                    string
}

func main() {
	tmpl := template.Must(template.New("editor").Parse(editorTemplate))
	features := featureSet()
	opts := format.Options{LangVersion: "go1.26"}
	if err := opts.Extra.Set("true"); err != nil {
		log.Fatal(err)
	}
	for dialect, statements := range dialects() {
		var buf bytes.Buffer
		buf.WriteString(header)
		for _, s := range statements {
			if err := tmpl.Execute(&buf, s.editor(features)); err != nil {
				log.Fatal(err)
			}
		}
		code, err := format.Source(buf.Bytes(), opts)
		if err != nil {
			log.Fatalf("format %s: %v", dialect, err)
		}
		path := filepath.Join("dialect", dialect, "dialect", "editors.gen.go")
		if err := os.WriteFile(path, code, 0o600); err != nil {
			log.Fatal(err)
		}
	}
}

func (s statement) editor(features map[string]feature) editor {
	lower := strings.ToLower(s.kind)
	e := editor{Kind: s.kind, Editor: s.kind + "Editor", Private: lower + "Editor", State: lower + "State"}
	for name := range strings.FieldsSeq(s.features) {
		f, ok := features[name]
		if !ok {
			panic("unknown editor feature: " + name)
		}
		for field := range strings.FieldsSeq(f.fields) {
			if !slices.Contains(e.Fields, field) {
				e.Fields = append(e.Fields, field)
			}
		}
		for line := range strings.Lines(strings.TrimSpace(f.methods)) {
			sig, body, explicit := strings.Cut(strings.TrimSpace(line), " | ")
			sig = strings.ReplaceAll(sig, "EDITOR", e.Editor)
			if explicit {
				body = strings.ReplaceAll(body, "q.", "e.q.")
			} else {
				body = forward(sig)
			}
			e.Methods = append(e.Methods, method{sig, body})
		}
		switch name {
		case "callbacks":
			e.Callbacks = true
		case "where":
			e.Flags = append(e.Flags, "ownedWhere")
		case "insert", "values":
			e.Flags = append(e.Flags, "ownedRows")
		case "pgMultiFrom":
			e.Flags = append(e.Flags, "ownedRefs")
			if s.kind == "Update" {
				e.TableRefs = "FromItems"
			} else {
				e.TableRefs = "UsingItems"
			}
		}
	}
	return e
}

func forward(sig string) string {
	name, params, _ := strings.Cut(sig, "(")
	expr, err := parser.ParseExpr("func(" + params)
	if err != nil {
		panic(err)
	}
	fn := expr.(*ast.FuncType)
	var args []string
	for _, p := range fn.Params.List {
		for _, id := range p.Names {
			arg := id.Name
			if _, variadic := p.Type.(*ast.Ellipsis); variadic {
				arg += "..."
			}
			args = append(args, arg)
		}
	}
	call := fmt.Sprintf("e.q.%s(%s)", name, strings.Join(args, ", "))
	if fn.Results != nil {
		return "return " + call
	}
	return call
}

